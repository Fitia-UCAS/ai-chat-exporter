/* ChatGPT API client and conversation parser. */
(function initChatGPTAdapter(root) {
  'use strict';

  const NS = root.ChatExportKit;

  const PLATFORM = 'ChatGPT';

  function isConversationPage() {
    const path = location.pathname.replace(/\/+$/, '');
    return /(?:^|\/)c\/[^/?#]+$/i.test(path) || /^\/share\/[^/?#]+$/i.test(path);
  }

  function getConversationLocation() {
    const conversation = location.pathname.match(/(?:^|\/)c\/([^/?#]+)/i);
    if (conversation) return { id: conversation[1], shared: false };

    const shared = location.pathname.match(/^\/share\/([^/?#]+)/i);
    if (shared) return { id: shared[1], shared: true };

    throw new Error('请先打开一个具体的 ChatGPT 对话。');
  }

  async function getAccessToken() {
    try {
      const response = await fetch('/api/auth/session', {
        credentials: 'include',
        cache: 'no-store',
      });
      if (!response.ok) return '';
      const session = await response.json();
      return session && session.accessToken ? session.accessToken : '';
    } catch {
      return '';
    }
  }

  async function fetchConversation(current) {
    const headers = { accept: '*/*' };
    if (!current.shared) {
      const accessToken = await getAccessToken();
      if (accessToken) headers.authorization = `Bearer ${accessToken}`;
    }

    const endpoint = current.shared
      ? `/backend-api/share/${encodeURIComponent(current.id)}`
      : `/backend-api/conversation/${encodeURIComponent(current.id)}`;
    const response = await fetch(endpoint, {
      credentials: 'include',
      cache: 'no-store',
      headers,
    });

    if (!response.ok) {
      const hint = response.status === 401 || response.status === 403
        ? '（登录状态可能已失效，请刷新页面后重试）'
        : response.status === 404 ? '（对话不存在或没有访问权限）' : '';
      throw new Error(`无法读取完整对话（HTTP ${response.status}）${hint}。`);
    }

    const payload = await response.json();
    const conversation = payload && payload.mapping
      ? payload
      : payload && payload.data && payload.data.mapping ? payload.data : payload;
    if (!conversation || !conversation.mapping) {
      throw new Error('ChatGPT 返回了无法识别的对话数据，内部接口可能已经更新。');
    }
    return conversation;
  }

  function joinStrings(value, separator) {
    const collected = [];
    const walk = (node) => {
      if (typeof node === 'string') collected.push(node);
      else if (Array.isArray(node)) node.forEach(walk);
    };
    walk(value);
    return collected.map((item) => item.trim()).filter(Boolean).join(separator || '\n');
  }

  function partText(part) {
    if (typeof part === 'string') return part;
    if (!part || typeof part !== 'object') return '';
    if (typeof part.text === 'string') return part.text;
    if (typeof part.content === 'string') return part.content;
    return '';
  }

  function pointerName(pointer, mimeType) {
    const id = String(pointer || '').split('/').pop() || 'image';
    const extension = /png/i.test(mimeType) ? 'png'
      : /jpe?g/i.test(mimeType) ? 'jpg'
        : /webp/i.test(mimeType) ? 'webp' : 'bin';
    return `${id}.${extension}`;
  }

  function imagePart(part) {
    if (!part || typeof part !== 'object') return null;
    if (part.content_type !== 'image_asset_pointer' && !part.asset_pointer) return null;
    const ref = String(part.asset_pointer || '');
    if (!ref) return null;
    const mimeType = part.mime_type || (part.metadata && part.metadata.mime_type) || 'image/png';
    return {
      name: part.name || part.filename || pointerName(ref, mimeType),
      kind: 'image',
      mimeType,
      size: Number.isFinite(part.size_bytes) ? part.size_bytes : null,
      ref,
      status: part.metadata && part.metadata.dalle ? 'Generated by model' : '',
    };
  }

  function readContent(message) {
    const content = message && message.content ? message.content : {};
    const type = String(content.content_type || '');
    const parts = Array.isArray(content.parts) ? content.parts : [];
    const metadata = (message && message.metadata) || {};
    const author = (message && message.author) || {};
    const images = [];
    for (const part of parts) {
      const image = imagePart(part);
      if (image) images.push(image);
    }
    const reasoning = type === 'thought' || type === 'thoughts' || type === 'reasoning_recap'
      || author.name === 'thought'
      || message.recipient === 'thought'
      || metadata.reasoning_status === 'is_reasoning';

    if (type === 'thoughts') {
      const thoughts = Array.isArray(content.thoughts) ? content.thoughts : [];
      const text = thoughts
        .map((item) => {
          if (typeof item === 'string') return item;
          if (!item || typeof item !== 'object') return '';
          const body = typeof item.content === 'string' ? item.content : '';
          const summary = typeof item.summary === 'string' ? item.summary : '';
          if (summary) return body ? `**${summary}**\n${body}` : `**${summary}**`;
          return body;
        })
        .filter(Boolean)
        .join('\n\n')
        || joinStrings(parts.map(partText), '\n')
        || (typeof content.text === 'string' ? content.text : '');
      return { text: '', thinking: text, thinkingLabel: 'Reasoning', images };
    }

    if (type === 'reasoning_recap') {
      const text = (typeof content.content === 'string' ? content.content : '')
        || (typeof content.text === 'string' ? content.text : '')
        || joinStrings(parts.map(partText), '\n');
      return { text: '', thinking: text, thinkingLabel: 'Reasoning recap', images };
    }

    if (type === 'thought') {
      const text = joinStrings(parts.map(partText), '\n')
        || (typeof content.text === 'string' ? content.text : '')
        || (typeof content.content === 'string' ? content.content : '');
      return { text: '', thinking: text, thinkingLabel: 'Reasoning', images };
    }

    if (type === 'user_editable_context') {
      return {
        text: '',
        thinking: '',
        images,
        systemContext: joinStrings(parts.map(partText), '\n') || content.text || content.content || '',
      };
    }

    if (type === 'code') {
      const code = typeof content.text === 'string' && content.text
        ? content.text
        : joinStrings(parts.map(partText), '\n');
      return { text: code, thinking: '', images, codeLanguage: content.language || '', isCode: true };
    }

    const chunks = [];
    const thoughts = [];
    for (const part of parts) {
      const text = partText(part);
      if (!text) continue;
      const thoughtPart = reasoning || (part && typeof part === 'object' && part.content_type === 'thought');
      (thoughtPart ? thoughts : chunks).push(text);
    }

    if (!chunks.length && typeof content.text === 'string') {
      (reasoning ? thoughts : chunks).push(content.text);
    }
    return {
      text: chunks.join('\n\n').trim(),
      thinking: thoughts.join('\n\n').trim(),
      thinkingLabel: 'Reasoning',
      images,
    };
  }

  function metadataAttachments(message) {
    const list = message && message.metadata && message.metadata.attachments;
    if (!Array.isArray(list)) return [];
    return list
      .filter((item) => item && typeof item === 'object')
      .map((item) => {
        const direct = item.download_url || item.url || item.download_link || item.fileDownloadUrl || '';
        return {
          name: item.name || item.filename || item.id || 'Untitled attachment',
          kind: /^image\//i.test(item.mime_type || '') ? 'image' : 'file',
          mimeType: item.mime_type || '',
          size: Number.isFinite(item.size) ? item.size : null,
          ref: direct || (item.id ? `file-service://${item.id}` : ''),
          libraryFileId: item.library_file_id || '',
          status: item.id || direct ? '' : 'No file id provided',
        };
      });
  }

  function messageTime(message) {
    const created = message && message.create_time;
    return typeof created === 'number' ? created : null;
  }

  function branchLabel(node, mapping) {
    const parent = node && node.parent ? mapping[node.parent] : null;
    const siblings = parent && Array.isArray(parent.children) ? parent.children : null;
    if (!siblings || siblings.length < 2) return '';
    const index = siblings.indexOf(node.id);
    return `Branch ${index >= 0 ? index + 1 : 1}/${siblings.length}`;
  }

  function orderNodes(conversation) {
    const mapping = conversation.mapping || {};
    const chain = [];
    const visited = new Set();
    let nodeId = conversation.current_node;

    while (nodeId && mapping[nodeId] && !visited.has(nodeId)) {
      visited.add(nodeId);
      chain.push(mapping[nodeId]);
      nodeId = mapping[nodeId].parent;
    }

    if (chain.length) return chain.reverse();

    return Object.values(mapping)
      .filter((node) => node && node.message)
      .sort((left, right) => (left.message.create_time || 0) - (right.message.create_time || 0));
  }

  function isHiddenMessage(message) {
    const metadata = (message && message.metadata) || {};
    return Boolean(metadata.is_visually_hidden_from_conversation || metadata.is_user_system_message);
  }

  function buildMessages(conversation, tier) {
    const mapping = conversation.mapping || {};
    const nodes = orderNodes(conversation);
    const messages = [];
    const notes = [];
    let lastAssistant = null;
    let skippedSystem = 0;
    let skippedHidden = 0;

    for (const node of nodes) {
      const message = node && node.message;
      if (!message) continue;

      const role = NS.normalizeRole(message.author && message.author.role);
      const metadata = message.metadata || {};
      if (metadata.is_user_system_message) {
        skippedSystem++;
        continue;
      }

      const content = readContent(message);
      const hidden = isHiddenMessage(message);

      if (role === 'tool') {
        const output = content.text || '';
        if (lastAssistant && output) {
          const target = lastAssistant.toolCalls[lastAssistant.toolCalls.length - 1];
          if (target) {
            target.output = target.output ? `${target.output}\n\n${output}` : output;
            target.outputLanguage = 'text';
          } else {
            lastAssistant.toolCalls.push({ name: 'tool', input: '', output, outputLanguage: 'text' });
          }
        }
        continue;
      }

      if (role !== 'user' && role !== 'assistant' && role !== 'system') continue;
      if (hidden && role === 'system') {
        skippedHidden++;
        continue;
      }
      if (tier === 'minimal' && hidden) {
        skippedHidden++;
        continue;
      }
      if (tier === 'minimal' && role === 'system') {
        skippedSystem++;
        continue;
      }

      const attachments = [...(content.images || []), ...metadataAttachments(message)];
      const toolCalls = [];

      const recipient = String(message.recipient || '');
      if (content.isCode && recipient && recipient !== 'all' && recipient !== 'assistant') {
        toolCalls.push({
          name: recipient,
          input: content.text,
          inputLanguage: content.codeLanguage || 'text',
          output: '',
          outputLanguage: 'text',
          status: metadata.aggregate_result && metadata.aggregate_result.status
            ? String(metadata.aggregate_result.status)
            : '',
          // aggregate_result is machine data; use it only when the tool output is unavailable.
          aggregate: metadata.aggregate_result && typeof metadata.aggregate_result === 'object'
            ? metadata.aggregate_result
            : null,
        });
      }

      const record = {
        role,
        text: toolCalls.length ? '' : content.text,
        thinking: tier === 'minimal' ? '' : (content.thinking || ''),
        thinkingLabel: content.thinkingLabel || 'Reasoning',
        toolCalls,
        attachments,
        time: messageTime(message),
        hidden,
        branch: tier === 'detailed' ? branchLabel(node, mapping) : '',
        meta: {
          id: message.id || node.id || '',
          parentId: node.parent || '',
          model: metadata.model_slug || '',
          reasoning: metadata.thinking_effort || '',
        },
      };

      if (!NS.hasRenderableContent(NS.createMessage(record), tier)) continue;

      messages.push(record);
      if (role === 'assistant') lastAssistant = record;
      else lastAssistant = null;
    }

    for (const message of messages) {
      for (const call of message.toolCalls) {
        if (!call.output && call.aggregate) {
          call.output = NS.safeJson(call.aggregate);
          call.outputLanguage = 'json';
        }
        delete call.aggregate;
      }
    }

    if (skippedSystem) notes.push(`Skipped ${skippedSystem} system/custom-instruction messages (not part of the visible transcript).`);
    if (skippedHidden) notes.push(`Skipped ${skippedHidden} visually hidden messages (not included in Minimal).`);

    const branchCount = countBranchMessages(conversation, nodes);
    if (branchCount > 0 && tier !== 'detailed') {
      notes.push(`${branchCount} messages exist on other branches; only the current branch was exported.`);
    } else if (branchCount > 0) {
      notes.push(`${branchCount} messages exist on other branches; Detailed marks branch positions without expanding their text.`);
    }

    return { messages, notes };
  }

  function countBranchMessages(conversation, activeNodes) {
    const mapping = conversation.mapping || {};
    const active = new Set(activeNodes.map((node) => node.id));
    let count = 0;
    for (const [id, node] of Object.entries(mapping)) {
      if (active.has(id)) continue;
      const message = node && node.message;
      if (!message) continue;
      const role = NS.normalizeRole(message.author && message.author.role);
      if (role === 'user' || role === 'assistant') count++;
    }
    return count;
  }


  function fileIdFromRef(ref) {
    const match = String(ref || '').match(/^(file-service|sediment):\/\/(.+)$/);
    if (!match) return null;
    return { kind: match[1], id: match[2] };
  }

  async function readMedia(url, mimeType) {
    const target = new URL(String(url || ''), location.href);
    if (target.protocol !== 'https:') throw new Error('只允许读取 HTTPS 资源');

    if (target.origin === location.origin) {
      const response = await fetch(target.href, { credentials: 'include', cache: 'no-store' });
      if (!response.ok) throw new Error(`资源请求失败（HTTP ${response.status}）`);
      const bytes = new Uint8Array(await response.arrayBuffer());
      if (!bytes.length) throw new Error('资源内容为空');
      return { bytes, mimeType: response.headers.get('content-type') || mimeType || '' };
    }

    const media = await NS.fetchMedia(target.href);
    return { bytes: media.bytes, mimeType: media.mimeType || mimeType || '' };
  }

  async function resolveAttachmentFile(attachment) {
    if (/^https?:\/\//i.test(attachment.ref || '')) {
      const media = await readMedia(attachment.ref, attachment.mimeType);
      return { bytes: media.bytes, mimeType: media.mimeType || attachment.mimeType };
    }

    const parsed = fileIdFromRef(attachment.ref);
    if (!parsed) return null;
    if (parsed.kind === 'sediment') return null;

    const accessToken = await getAccessToken();
    const headers = { accept: 'application/json' };
    if (accessToken) headers.authorization = `Bearer ${accessToken}`;

    let conversationId = '';
    try {
      conversationId = getConversationLocation().id;
    } catch {}

    const ids = [...new Set([parsed.id, attachment.libraryFileId].filter(Boolean))];
    const endpoints = [];
    for (const id of ids) {
      if (conversationId) {
        endpoints.push(`/backend-api/files/download/${encodeURIComponent(id)}?conversation_id=${encodeURIComponent(conversationId)}&inline=false`);
        endpoints.push(`/backend-api/conversation/${encodeURIComponent(conversationId)}/attachment/${encodeURIComponent(id)}/download`);
      }
      endpoints.push(`/backend-api/files/download/${encodeURIComponent(id)}`);
      endpoints.push(`/backend-api/files/${encodeURIComponent(id)}/download`);
    }

    let response = null;
    let status = 0;
    for (const endpoint of endpoints) {
      response = await fetch(endpoint, {
        credentials: 'include',
        cache: 'no-store',
        headers,
      });
      status = response.status;
      if (response.ok) break;
    }
    if (!response || !response.ok) throw new Error(`文件接口返回 HTTP ${status}`);

    const payload = await response.json();
    const downloadUrl = payload && (payload.download_url || payload.url);
    if (!downloadUrl) throw new Error('文件接口没有返回下载地址');

    const media = await readMedia(downloadUrl, payload.mime_type || attachment.mimeType);
    return { bytes: media.bytes, mimeType: payload.mime_type || media.mimeType || attachment.mimeType };
  }

  async function collectResources(messages, collector) {
    for (const message of messages) {
      for (const attachment of message.attachments) {
        if (attachment.resourceId) continue;
        if (!attachment.ref) {
          attachment.status = attachment.status || 'No accessible reference provided by the platform';
          continue;
        }
        try {
          const file = await resolveAttachmentFile(attachment);
          if (!file || !file.bytes || !file.bytes.length) {
            attachment.status = 'Could not fetch the original file (no download or expired)';
            continue;
          }
          await NS.storeAttachment(
            attachment,
            file.bytes,
            file.mimeType || attachment.mimeType,
            message.index,
            collector,
          );
        } catch (error) {
          attachment.status = `Could not fetch the original file: ${error && error.message ? error.message : String(error)}`;
        }
      }
    }
    return collector.entries();
  }

  async function read({ tier }) {
    const current = getConversationLocation();
    const conversation = await fetchConversation(current);
    const { messages, notes } = buildMessages(conversation, tier);

    if (current.shared) {
      notes.push('This is a shared link; some attachments may not be readable with the current session.');
    }

    return {
      platform: PLATFORM,
      method: 'API',
      conversationId: current.id,
      title: conversation.title || document.title || 'ChatGPT conversation',
      url: location.href,
      messages,
      notes,
      pages: 1,
    };
  }

  root.ChatGPTAdapter = {
    platform: 'chatgpt',
    platformLabel: PLATFORM,
    isConversationPage,
    read,
    collectResources,
    internals: { buildMessages, readContent, orderNodes, branchLabel, countBranchMessages },
  };
})(typeof globalThis !== 'undefined' ? globalThis : this);
